"""Configure a new installation and seed starter records without resetting existing data."""

import argparse
import asyncio
import json
import os
import secrets
import sys
from pathlib import Path
from urllib.parse import urlsplit

from cryptography.fernet import Fernet
from dotenv import dotenv_values
from sqlalchemy import func, select

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "backend"))

from app.core.config import Settings  # noqa: E402
from app.db.models import Agent, Team, TeamAgent, User, WorkflowTemplate  # noqa: E402
from app.db.session import database, migrate  # noqa: E402
from app.services.seed import PRESETS, seed, template_graph  # noqa: E402
from app.services.workflow_validator import validate_graph  # noqa: E402


class InstallSettings(Settings):
    @classmethod
    def settings_customise_sources(cls, settings_cls, init_settings, **kwargs):
        # Installer configuration must never fall through to the IDE's environment.
        return (init_settings,)


def write_new_env(path, values):
    """Exclusive create protects existing secrets and user configuration on reruns."""
    if path.exists():
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    content = "# Generated by 1devTeams installer. Keep this file private.\n"
    for key, value in values.items():
        value = str(value)
        if any(char in value for char in "\r\n\0"):
            raise ValueError(f"Invalid newline in {key}")
        content += key + "='" + value.replace("\\", "\\\\").replace("'", "\\'") + "'\n"
    descriptor = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(descriptor, "w", encoding="utf-8", newline="\n") as stream:
        stream.write(content)
    if os.name == "nt":
        # Limit newly generated credentials to the installing Windows account.
        import subprocess

        identity = subprocess.check_output(["whoami"], text=True).strip()
        subprocess.run(
            ["icacls", str(path), "/inheritance:r", "/grant:r", f"{identity}:(F)"],
            check=True,
            stdout=subprocess.DEVNULL,
        )
    return True


def configure(root, args):
    if "@" not in args.admin_email:
        raise ValueError("Specify a valid owner email with --admin-email")
    ports = dotenv_values(root / ".env", interpolate=False) if (root / ".env").exists() else {}
    frontend = int(ports.get("FRONTEND_PORT") or args.frontend_port)
    backend = int(ports.get("BACKEND_PORT") or args.backend_port)
    if frontend == backend or not all(1 <= port <= 65535 for port in (frontend, backend)):
        raise ValueError("Invalid ports in root .env")
    origins = [f"http://localhost:{frontend}", f"http://127.0.0.1:{frontend}"]
    if args.public_url:
        parsed = urlsplit(args.public_url)
        if (
            parsed.scheme not in {"http", "https"}
            or not parsed.hostname
            or parsed.username
            or parsed.password
            or parsed.query
            or parsed.fragment
            or parsed.path not in {"", "/"}
        ):
            raise ValueError("--public-url must be an HTTP(S) origin, without path or credentials")
        origins.append(f"{parsed.scheme}://{parsed.netloc}")
    workspace = Path(args.workspace).expanduser().resolve() if args.workspace else root / "workspaces"
    if ";" in str(workspace):
        raise ValueError("Workspace path cannot contain a semicolon")
    tools = root / ".tools"
    tools.mkdir(parents=True, exist_ok=True)
    write_new_env(root / ".env", {"FRONTEND_PORT": frontend, "BACKEND_PORT": backend})
    workspace.mkdir(parents=True, exist_ok=True)
    data = root / "backend/data"
    data.mkdir(parents=True, exist_ok=True)
    values = dict(dotenv_values(ROOT / "backend/.env.example", interpolate=False))
    values = {key: value for key, value in values.items() if value is not None}
    values.update(
        {
            "JWT_SECRET": secrets.token_urlsafe(48),
            "APP_SECRET_KEY": Fernet.generate_key().decode(),
            "BOOTSTRAP_ADMIN_EMAIL": args.admin_email,
            "BOOTSTRAP_ADMIN_PASSWORD": "123456",
            "DATABASE_URL": "sqlite+aiosqlite:///" + (data / "aiteams.db").as_posix(),
            "CHECKPOINT_DB": str(data / "checkpoints.db"),
            "DATA_DIR": str(data),
            "ALLOWED_WORKSPACE_ROOTS": str(workspace),
            "CORS_ORIGINS": ",".join(dict.fromkeys(origins)),
            "ACP_INHERIT_PROVIDER_ENV": "false",
            "TRUSTED_NATIVE_ACP": str(args.trust_native_agents).lower(),
            "ENABLE_REMOTE_TERMINAL": str(args.enable_remote_terminal).lower(),
        }
    )
    created = write_new_env(root / "backend/.env", values)
    write_new_env(
        root / "frontend/.env",
        {
            "BACKEND_URL": f"http://127.0.0.1:{backend}",
            "NEXT_PUBLIC_API_URL": f"http://127.0.0.1:{backend}",
        },
    )
    (tools / "install-state.json").write_text(
        json.dumps({"frontend_port": frontend, "backend_port": backend}), encoding="utf-8"
    )
    return created


async def initialize(env_file):
    # Do not inherit an unrelated IDE/database URL from the installer's environment.
    values = {
        key.lower(): value
        for key, value in dotenv_values(env_file, interpolate=False).items()
        if value is not None
    }
    settings = InstallSettings(_env_file=None, **values)
    if settings.jwt_secret.get_secret_value() == "replace-with-a-random-local-secret":
        raise ValueError("Existing backend/.env still has a placeholder JWT_SECRET; configure it first")
    await asyncio.to_thread(migrate, settings.database_url)
    engine, sessions = database(settings.database_url)
    try:
        async with sessions() as db:
            if not await db.scalar(select(func.count()).select_from(User)):
                if (
                    not settings.bootstrap_admin_email
                    or not settings.bootstrap_admin_password
                    or not settings.bootstrap_admin_password.get_secret_value()
                ):
                    raise ValueError("Configure BOOTSTRAP_ADMIN_EMAIL and BOOTSTRAP_ADMIN_PASSWORD")
            await seed(db, settings)
            security = await db.scalar(select(Agent).where(Agent.handle == "@security"))
            if security is None:
                db.add(
                    Agent(
                        handle="@security",
                        display_name="Security Reviewer",
                        role_key="SECURITY",
                        runtime="claude-code",
                        permission_profile=PRESETS["read_only"],
                        is_builtin=True,
                        system_prompt=(
                            "Review code for security issues. Verify findings with file references. "
                            "Do not modify files or commit. Finish with @@ROUTE: pass or @@ROUTE: fail."
                        ),
                    )
                )
                await db.flush()
            agents = list((await db.scalars(select(Agent))).all())
            by_handle = {agent.handle: agent for agent in agents}
            teams = {
                "Feature Delivery Squad": [
                    "@leader",
                    "@ba",
                    "@designer",
                    "@planner",
                    "@developer",
                    "@tester",
                    "@devops",
                ],
                "Security Review Squad": ["@ba", "@developer", "@security", "@tester", "@devops"],
            }
            for name, handles in teams.items():
                if await db.scalar(select(Team.id).where(Team.name == name)):
                    continue
                team = Team(name=name, description="Starter team created by the installer")
                db.add(team)
                await db.flush()
                db.add_all(
                    [
                        TeamAgent(team_id=team.id, agent_id=by_handle[handle].id, position=index)
                        for index, handle in enumerate(handles)
                    ]
                )
            for key in ["blank", "bugfix_default", "add_feature", "bugfix_with_security_review"]:
                if await db.scalar(select(WorkflowTemplate.id).where(WorkflowTemplate.key == key)):
                    continue
                graph = template_graph(key, agents)
                errors = validate_graph(graph, agents)
                if errors:
                    raise ValueError(f"Starter template {key} is invalid: {'; '.join(errors)}")
                by_id = {agent.id: agent for agent in agents}
                for node in graph.nodes:
                    if node.type in {"agent", "git_release"}:
                        agent = by_id[node.data["agent_id"]]
                        node.data.update(agent_role=agent.role_key, agent_handle=agent.handle)
                db.add(WorkflowTemplate(key=key, graph=graph.model_dump(), instructions={}))
            await db.commit()
            return {
                model.__tablename__: await db.scalar(select(func.count()).select_from(model))
                for model in [User, Agent, Team, WorkflowTemplate]
            }
    finally:
        await engine.dispose()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--admin-email", default="owner@example.com")
    parser.add_argument("--workspace", default="")
    parser.add_argument("--frontend-port", type=int, default=3060)
    parser.add_argument("--backend-port", type=int, default=8060)
    parser.add_argument("--public-url", default="")
    parser.add_argument("--trust-native-agents", action="store_true")
    parser.add_argument("--enable-remote-terminal", action="store_true")
    parser.add_argument("--skip-providers", action="store_true")
    parser.add_argument("--skip-browser", action="store_true")
    args = parser.parse_args()
    created = configure(ROOT, args)
    print(json.dumps(asyncio.run(initialize(ROOT / "backend/.env"))))
    print(
        "Initial Owner password: 123456. Change it immediately after login. "
        "The owner email is stored in backend/.env (BOOTSTRAP_ADMIN_EMAIL)."
        if created
        else "Existing configuration and account passwords were preserved."
    )


if __name__ == "__main__":
    main()
